(function () {
    'use strict';

    var state = {
        data: null,
        loading: null,
        activeField: null,
        triggerClass: 'nacresearch-trigger',
        modal: null,
        refs: null,
        resultLimit: 100,
        debounceMs: 120,
        dataUrl: '/plugins/nacresearch/data/nacre.json',
        buttonLabel: 'NACRE',
        modalTitle: 'Recherche de code NACRE'
    };

    function readMeta(name, fallback) {
        var tag = document.querySelector('meta[name="' + name + '"]');
        return tag && tag.content ? tag.content : fallback;
    }

    function loadRuntimeConfig() {
        state.resultLimit = parseInt(readMeta('nacresearch:result-limit', String(state.resultLimit)), 10) || state.resultLimit;
        state.debounceMs = parseInt(readMeta('nacresearch:debounce-ms', String(state.debounceMs)), 10) || state.debounceMs;
        state.dataUrl = readMeta('nacresearch:data-url', state.dataUrl);
        state.buttonLabel = readMeta('nacresearch:button-label', state.buttonLabel);
        state.modalTitle = readMeta('nacresearch:modal-title', state.modalTitle);
    }

    function fetchData() {
        if (state.data) {
            return Promise.resolve(state.data);
        }

        if (state.loading) {
            return state.loading;
        }

        state.loading = window.fetch(state.dataUrl, { credentials: 'same-origin' })
            .then(function (response) {
                if (!response.ok) {
                    throw new Error('Impossible de charger les données NACRE.');
                }
                return response.json();
            })
            .then(function (payload) {
                state.data = Array.isArray(payload) ? payload : [];
                return state.data;
            })
            .finally(function () {
                state.loading = null;
            });

        return state.loading;
    }

    function normalize(value) {
        return String(value || '')
            .normalize('NFD')
            .replace(/[\u0300-\u036f]/g, '')
            .toLowerCase()
            .trim();
    }

    function isInFormCatalog() {
        return window.location.pathname.includes('/Form/Render/');
    }

    function isTicketForm() {
        // Check if we're rendering a Ticket form (new or old interface)
        var pathname = window.location.pathname;
        // New FormRenderer interface: /Ticket/
        if (pathname.includes('/Ticket/')) {
            return true;
        }
        // Old interface: /front/ticket.form.php
        if (pathname.includes('/ticket.form.php')) {
            return true;
        }
        return false;
    }

    function isInsideItilObjectForm(field) {
        // Authoritative DOM-based exclusion: never activate inside a Ticket,
        // Problem or Change (ITIL object) form, regardless of which URL/rendering
        // path GLPI used to reach it. URL string-matching alone (isTicketForm)
        // already proved fragile once — GLPI 11 renders ticket creation through
        // the same Form Renderer engine as the Form Catalog, so the URL can
        // contain /Form/Render/ even for a genuine ticket.
        return !!(
            field.closest('.itil-object-fields')
            || field.closest('#itil-data')
            // Prefix match: the numeric suffix is a per-request random id
            // generated by GLPI's Fields plugin, never stable.
            || field.closest('[id^="plugin_fields_container_"]')
        );
    }

    function getFormRendererQuestion(field) {
        return field.closest('[data-glpi-form-renderer-question]');
    }

    function fieldMatches(field) {
        // Cheap URL-based first pass, kept as defense-in-depth for the legacy
        // /front/ticket.form.php interface, which doesn't use the
        // itil-object-fields DOM markup checked below.
        if (isTicketForm()) {
            return false;
        }

        if (isInsideItilObjectForm(field)) {
            return false;
        }

        // Only enable in Form/Render catalog (not in profiles)
        if (!isInFormCatalog()) {
            return false;
        }

        var question = getFormRendererQuestion(field);
        // Positive confirmation: a genuine Form Catalog question is always
        // wrapped in [data-glpi-form-renderer-question]; an ITIL object field
        // is not. The URL alone cannot tell the two apart (see above).
        if (!question) {
            return false;
        }

        // Skip checkboxes (used in profile tabs)
        if (field.type === 'checkbox') {
            return false;
        }

        var labels = Array.prototype.map.call(field.labels || [], function (label) {
            return label.textContent;
        });
        labels.push(question.getAttribute('aria-label'));
        var candidates = [field.name, field.id, field.placeholder, field.getAttribute('aria-label')].concat(labels);
        return candidates.some(function (value) {
            return normalize(value).indexOf('nacre') !== -1;
        });
    }

    function createModal() {
        if (state.modal) {
            return state.modal;
        }

        var modal = document.createElement('div');
        modal.className = 'nacresearch-modal';
        modal.hidden = true;
        modal.innerHTML = [
            '<div class="nacresearch-modal__dialog" role="dialog" aria-modal="true" aria-labelledby="nacresearch-modal-title">',
            '  <div class="nacresearch-modal__header">',
            '    <h2 id="nacresearch-modal-title">' + escapeHtml(state.modalTitle) + '</h2>',
            '    <button type="button" class="btn btn-outline-secondary" data-nacresearch-close>Fermer</button>',
            '  </div>',
            '  <div class="nacresearch-modal__body">',
            '    <input type="search" class="form-control nacresearch-modal__search" placeholder="Rechercher par code, libellé ou mot-clé" data-nacresearch-search>',
            '    <div class="nacresearch-modal__status" data-nacresearch-status>Chargement des données…</div>',
            '    <div class="nacresearch-modal__results" data-nacresearch-results></div>',
            '  </div>',
            '  <div class="nacresearch-modal__footer">',
            '    <span class="nacresearch-modal__empty" data-nacresearch-empty hidden>Aucun résultat pour cette recherche.</span>',
            '    <button type="button" class="btn btn-secondary" data-nacresearch-close>Annuler</button>',
            '  </div>',
            '</div>'
        ].join('');

        document.body.appendChild(modal);

        var refs = {
            search: modal.querySelector('[data-nacresearch-search]'),
            status: modal.querySelector('[data-nacresearch-status]'),
            results: modal.querySelector('[data-nacresearch-results]'),
            empty: modal.querySelector('[data-nacresearch-empty]')
        };

        modal.querySelectorAll('[data-nacresearch-close]').forEach(function (button) {
            button.addEventListener('click', closeModal);
        });

        modal.addEventListener('click', function (event) {
            if (event.target === modal) {
                closeModal();
            }
        });

        refs.search.addEventListener('input', debounce(function () {
            renderResults(refs.search.value);
        }, state.debounceMs));

        document.addEventListener('keydown', function (event) {
            if (event.key === 'Escape' && state.modal && !state.modal.hidden) {
                closeModal();
            }
        });

        state.modal = modal;
        state.refs = refs;
        return modal;
    }

    function debounce(callback, wait) {
        var timer = null;
        return function () {
            var args = arguments;
            window.clearTimeout(timer);
            timer = window.setTimeout(function () {
                callback.apply(null, args);
            }, wait);
        };
    }

    function openModal(field) {
        state.activeField = field;
        var modal = createModal();
        modal.hidden = false;
        state.refs.status.textContent = 'Chargement des données…';
        state.refs.results.innerHTML = '';
        state.refs.empty.hidden = true;
        state.refs.search.value = field.value || '';

        fetchData()
            .then(function () {
                state.refs.status.textContent = state.data.length + ' codes disponibles.';
                renderResults(state.refs.search.value || field.value || '');
                state.refs.search.focus();
            })
            .catch(function (error) {
                state.refs.status.textContent = error.message;
            });
    }

    function closeModal() {
        if (!state.modal) {
            return;
        }

        state.modal.hidden = true;
        state.refs.results.innerHTML = '';
        state.refs.empty.hidden = true;
        if (state.activeField) {
            state.activeField.focus();
        }
    }

    // Niveau hiérarchique d'après la forme du code — utilisé en repli si le JSON
    // n'expose pas encore le champ `level` (fenêtre entre déploiement du code et
    // réécriture de nacre.json).
    function codeLevel(record) {
        if (record.level) {
            return record.level;
        }
        var parts = String(record.code || '').split('.');
        if (parts.length < 2) {
            return parts[0].length === 1 ? 1 : 2;
        }
        return parts[1].length === 1 ? 3 : 4;
    }

    function isSelectable(record) {
        if (typeof record.selectable === 'boolean') {
            return record.selectable;
        }
        return codeLevel(record) === 4;
    }

    // Garde-fou : masquer les lignes « NE PLUS UTILISER » même si nacre.json
    // n'a pas encore été reprocessé côté serveur.
    function isDeprecated(record) {
        return /ne plus utiliser/i.test(record.label || '');
    }

    // Une teinte stable par lettre de tête (famille NACRE), pour le liséré.
    function familyColor(code) {
        var letter = String(code || 'A').charAt(0).toUpperCase();
        var offset = letter.charCodeAt(0) - 65;
        if (offset < 0 || offset > 25) {
            offset = 0;
        }
        return 'hsl(' + Math.round(offset * (360 / 26)) + ', 60%, 42%)';
    }

    function renderResults(query) {
        var records = state.data || [];
        var normalizedTerms = normalize(query).split(/\s+/).filter(Boolean);
        var matches = records.filter(function (record) {
            if (isDeprecated(record)) {
                return false;
            }
            var haystack = normalize(record.search || [record.code, record.label].join(' '));
            return normalizedTerms.every(function (term) {
                return haystack.indexOf(term) !== -1;
            });
        });

        // Le plafond ne s'applique qu'aux codes : toutes les catégories
        // correspondantes restent visibles pour garder le fil hiérarchique.
        // Répartition round-robin par famille (lettre de tête) plutôt qu'un
        // simple ordre de fichier : sinon, avec une recherche large, le quota
        // se retrouve épuisé par les premières familles alphabétiques et les
        // familles suivantes n'affichent plus que des catégories sans codes.
        var categoryCount = 0;
        var totalMatchingCodes = 0;
        var codesByFamily = {};
        var familyOrder = [];
        matches.forEach(function (record) {
            if (!isSelectable(record)) {
                categoryCount += 1;
                return;
            }
            totalMatchingCodes += 1;
            var family = String(record.code || 'A').charAt(0).toUpperCase();
            if (!codesByFamily[family]) {
                codesByFamily[family] = [];
                familyOrder.push(family);
            }
            codesByFamily[family].push(record);
        });

        var selectedCodes = Object.create(null);
        var codeCount = 0;
        var exhausted = false;
        while (!exhausted && codeCount < state.resultLimit) {
            exhausted = true;
            for (var i = 0; i < familyOrder.length && codeCount < state.resultLimit; i += 1) {
                var bucket = codesByFamily[familyOrder[i]];
                if (bucket.length) {
                    selectedCodes[bucket.shift().code] = true;
                    codeCount += 1;
                    exhausted = false;
                }
            }
        }

        var shown = matches.filter(function (record) {
            return !isSelectable(record) || selectedCodes[record.code];
        });

        state.refs.results.innerHTML = '';
        state.refs.empty.hidden = shown.length !== 0;
        var truncated = codeCount < totalMatchingCodes;
        state.refs.status.textContent = !shown.length
            ? '0 résultat affiché.'
            : truncated
                ? codeCount + ' code(s) affiché(s) sur ' + totalMatchingCodes + ' correspondant(s) · '
                    + categoryCount + ' catégorie(s). Affinez votre recherche pour voir les codes restants.'
                : codeCount + ' code(s) · ' + categoryCount + ' catégorie(s) sur ' + records.length + '.';
        state.refs.status.classList.toggle('nacresearch-modal__status--truncated', truncated);

        shown.forEach(function (record) {
            var selectable = isSelectable(record);
            var level = codeLevel(record);
            var element = document.createElement(selectable ? 'button' : 'div');
            element.className = 'nacresearch-modal__result nacresearch-modal__result--level-' + level
                + (selectable ? '' : ' nacresearch-modal__result--category');
            element.style.setProperty('--nacre-family', familyColor(record.code));
            var meta = selectable
                ? 'Section ' + escapeHtml(record.section || '-') + ' · Division ' + escapeHtml(record.division || '-')
                : 'Catégorie · niveau ' + level;
            element.innerHTML = [
                '<span class="nacresearch-modal__result-code">' + escapeHtml(record.code) + '</span>',
                '<span>' + escapeHtml(record.label)
                    + (selectable ? '' : ' <span class="nacresearch-modal__result-badge">Catégorie</span>') + '</span>',
                '<span class="nacresearch-modal__result-meta">' + meta + '</span>'
            ].join('');
            if (selectable) {
                element.type = 'button';
                element.addEventListener('click', function () {
                    applySelection(record.code);
                });
            }
            state.refs.results.appendChild(element);
        });
    }

    function applySelection(code) {
        if (!state.activeField) {
            return;
        }

        state.activeField.value = code;
        state.activeField.dispatchEvent(new Event('input', { bubbles: true }));
        state.activeField.dispatchEvent(new Event('change', { bubbles: true }));
        closeModal();
    }

    function escapeHtml(value) {
        return String(value || '')
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#039;');
    }

    function injectButton(field) {
        if (
            field.type === 'hidden'
            || field.dataset.nacresearchEnhanced === '1'
            || !fieldMatches(field)
        ) {
            return;
        }

        field.dataset.nacresearchEnhanced = '1';

        var button = document.createElement('button');
        button.type = 'button';
        button.className = 'btn btn-outline-primary btn-sm ' + state.triggerClass;
        button.textContent = state.buttonLabel;
        button.addEventListener('click', function () {
            openModal(field);
        });

        field.insertAdjacentElement('afterend', button);
    }

    function scan(root) {
        var scope = root && root.querySelectorAll ? root : document;
        scope.querySelectorAll('input, textarea').forEach(injectButton);
    }

    function initObserver() {
        var observer = new MutationObserver(function (mutations) {
            mutations.forEach(function (mutation) {
                mutation.addedNodes.forEach(function (node) {
                    if (node.nodeType === Node.ELEMENT_NODE) {
                        if (node.matches && node.matches('input, textarea')) {
                            injectButton(node);
                        }
                        scan(node);
                    }
                });
            });
        });

        observer.observe(document.body, { childList: true, subtree: true });
    }

    function bootstrap() {
        loadRuntimeConfig();
        scan(document);
        initObserver();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', bootstrap);
    } else {
        bootstrap();
    }
})();
